# Writes Strings.Designer.cs from Strings.resx. Run it after you add or remove a string.
# WPF's temporary build can't see a class generated during the build, so this file is committed.
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
[xml]$english = Get-Content (Join-Path $repo 'Strings.resx') -Raw -Encoding UTF8
[xml]$turkish = Get-Content (Join-Path $repo 'Strings.tr.resx') -Raw -Encoding UTF8

$names = @($english.root.data.name | Sort-Object)
$missing = @($names | Where-Object { $_ -notin $turkish.root.data.name }) + @($turkish.root.data.name | Where-Object { $_ -notin $names })
if ($missing.Count -gt 0) { throw "These strings aren't in both languages: $($missing -join ', ')" }

$lines = @(
    '// <auto-generated>Written by tools/gen-strings.ps1 from Strings.resx.</auto-generated>'
    '#nullable enable'
    'using System.Globalization;'
    'using System.Resources;'
    ''
    'namespace Nimbus;'
    ''
    'internal static class Strings'
    '{'
    '    public static readonly ResourceManager ResourceManager = new("Nimbus.Strings", typeof(Strings).Assembly);'
    ''
    '    public static CultureInfo? Culture { get; set; }'
    ''
    '    private static string Get(string name) => ResourceManager.GetString(name, Culture) ?? name;'
    ''
)
$lines += $names | ForEach-Object { "    public static string $_ => Get(`"$_`");" }
$lines += '}'
[IO.File]::WriteAllText((Join-Path $repo 'Strings.Designer.cs'), ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
"Wrote $($names.Count) strings."
